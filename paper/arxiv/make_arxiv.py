"""Build the public arXiv source (arxiv/meridian.tex) from the full paper (meridian.tex).

The arXiv version differs only by these replacements: affiliations, the gate's answers, Jingyi's
job, the letter screenshot, and two caption notes. Edit the full paper, then run
    python3 arxiv/make_arxiv.py
from paper/. Every replacement must match exactly once, or the script stops.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE.parent / "meridian.tex").read_text()

R = [
    ("%% MERIDIAN: the Yi Town paper.", "\\pdfoutput=1\n%% MERIDIAN: the Yi Town paper (arXiv version, generated by arxiv/make_arxiv.py)."),
    ("\\pdfmapfile{+gbsnu.map}\n\\pdfmapfile{+gkaiu.map}", "\\pdfmapfile{=gbsnu.map}\n\\pdfmapfile{=gkaiu.map}"),
    ("\\author{Jingyi Chen}\n\\affiliation{\\institution{Yi Town}\\country{}}",
     "\\author{Jingyi Chen}\n\\authornote{Both authors made this work in and for Yi Town, \\url{https://jingyifan.love}.}\n"
     "\\affiliation{\\institution{Independent Researcher}\\city{Shenzhen}\\country{China}}"),
    ("\\authornote{Corresponding author.}\n\\affiliation{\\institution{Yi Town}\\country{}}",
     "\\authornote{Corresponding author.}\n\\affiliation{\\institution{Independent Researcher}\\city{College Station, Texas}\\country{USA}}"),
    ("Jingyi in Shenzhen, Guangdong, where she works in product management, and\nYifan in College Station, Texas, where he is a doctoral student.",
     "Jingyi in Shenzhen, Guangdong, and\nYifan in College Station, Texas."),
    ("The site at \\code{jingyifan.love} opens on a single question. The answer, a date both\nplayers know, is accepted in several spellings (\\code{9.20}, \\code{0920}, \\zh{9月20日},\n\\code{20260920}); it is reduced to its digits and compared by SHA-256 hash~\\cite{fips1804}, so the\nanswer is not written in the bundle.",
     "The site opens on a single question. The answer, a date both players know, is accepted in\nseveral spellings: it is reduced to its digits and compared by SHA-256 hash~\\cite{fips1804}, so\nthe answer is not written in the bundle."),
    ("{figures/page-letter.jpg}\\caption{The last letter}", "{figures/page-journey.jpg}\\caption{The journey list}"),
    ("(d) The\n  epilogue opens once both players have cleared the last level.}", "(d) The\n  journey as a list, for players who prefer it to the map.}"),
    ("(b) Name the place in the street view.", "(b) Name the place in the street view (photograph: Maarten Heerlien, CC~BY~2.0, via Wikimedia Commons)."),
    ("(d) Put the first days in order.", "(d) Put the first days in order (the photographs below are omitted here)."),
]
for old, new in R:
    n = src.count(old)
    if n != 1:
        raise SystemExit(f"expected one match, found {n}: {old[:60]!r}")
    src = src.replace(old, new)
(HERE / "meridian.tex").write_text(src)
print("wrote arxiv/meridian.tex")
