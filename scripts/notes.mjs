// Rebuild the mailbox list from the files in public/media/voice/notes/.
// Name each file  <date>-<sender>[-n].m4a  e.g. 2026-10-25-jingyi.m4a, 2026-10-25-jingyi-2.mp3
// (sender is jingyi or yifan: who recorded it). Length comes from afinfo (macOS) or ffprobe.
import { readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const DIR = 'public/media/voice/notes';
const OUT = 'src/features/voice/notes.ts';

function seconds(path) {
  try { return Math.round(parseFloat(/estimated duration: ([\d.]+)/.exec(execFileSync('afinfo', [path], { encoding: 'utf8' }))[1])); } catch { /* not macOS */ }
  try { return Math.round(parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path], { encoding: 'utf8' }))); } catch { return 0; }
}

const notes = [];
for (const f of readdirSync(DIR).sort()) {
  const m = /^(\d{4}-\d{2}-\d{2})-(jingyi|yifan)(?:-\d+)?\.(m4a|mp3|aac|wav|ogg)$/i.exec(f);
  if (!m) { if (!f.startsWith('README')) console.warn(`skipped ${f}: name it <date>-<jingyi|yifan>[-n].m4a`); continue; }
  notes.push({ src: `media/voice/notes/${f}`, from: m[2].toLowerCase(), date: m[1], seconds: seconds(`${DIR}/${f}`) });
}
notes.sort((a, b) => (a.date < b.date ? 1 : -1));

const body = notes.map((n) => `  { src: '${n.src}', from: '${n.from}', date: '${n.date}', seconds: ${n.seconds} },`).join('\n');
writeFileSync(OUT, `// Voice notes kept in the mailbox by the fountain: the little recordings we send each other.
// GENERATED by \`npm run notes\` from the files in public/media/voice/notes/ (see its README); do not edit by hand.
import type { PlayerId } from '../../core/quest';

export interface Note { src: string; from: PlayerId; date: string; seconds: number }

export const NOTES: Note[] = [
${body}
];

/** Notes addressed to \`player\`: the ones the other one sent, newest first, at most \`limit\`. */
export const notesFor = (player: PlayerId, limit = 8): Note[] =>
  NOTES.filter((n) => n.from !== player).sort((a, b) => (a.date < b.date ? 1 : -1)).slice(0, limit);
`);
console.log(`${notes.length} note(s) listed in ${OUT}`);
